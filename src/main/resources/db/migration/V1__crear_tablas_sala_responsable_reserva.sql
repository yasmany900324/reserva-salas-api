-- Necesario para combinar "=" (sala_id) y "&&" (rango de fechas) en la restricción de exclusión
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE sala (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20)  NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    CONSTRAINT uk_sala_codigo UNIQUE (codigo)
);

CREATE TABLE responsable (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL
);

CREATE TABLE reserva (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sala_id        BIGINT      NOT NULL REFERENCES sala (id),
    responsable_id BIGINT      NOT NULL REFERENCES responsable (id),
    inicio         TIMESTAMPTZ NOT NULL,
    fin            TIMESTAMPTZ NOT NULL,
    estado         VARCHAR(20) NOT NULL,
    CONSTRAINT ck_reserva_fin_posterior CHECK (fin > inicio),
    CONSTRAINT ck_reserva_estado CHECK (estado IN ('ACTIVA', 'CANCELADA')),
    -- Una sala no puede tener dos reservas activas que se crucen.
    -- Rango semiabierto [inicio, fin): 10:00-11:00 y 11:00-12:00 no chocan.
    CONSTRAINT ex_reserva_sin_solapamiento EXCLUDE USING gist (
        sala_id WITH =,
        tstzrange(inicio, fin, '[)') WITH &&
    ) WHERE (estado = 'ACTIVA')
);

-- El índice gist de la restricción ya cubre las búsquedas por sala y fechas
CREATE INDEX ix_reserva_responsable ON reserva (responsable_id);
